// Get current language from session
function getCurrentLang() {
    return $_SESSION['admin_lang'] ?? 'en';
}

// Set language
function setLang($lang) {
    if (in_array($lang, ['en', 'ku', 'ar'])) {
        $_SESSION['admin_lang'] = $lang;
    }
}

// Get translation
function __($key) {
    global $translations;
    $lang = getCurrentLang();
    return $translations[$lang][$key] ?? $translations['en'][$key] ?? $key;
}

// Check if RTL language
function isRTL() {
    return in_array(getCurrentLang(), ['ku', 'ar']);
}

// Get language direction
function getLangDir() {
    return isRTL() ? 'rtl' : 'ltr';
}

// Get language name
function getLangName($code) {
    $names = [
        'en' => 'English',
        'ku' => 'کوردی',
        'ar' => 'العربية'
    ];
    return $names[$code] ?? $code;
}

// Get localized field value (for database records with name, name_ku, name_ar fields)
function getLocalizedName($row, $field = 'name') {
    $lang = getCurrentLang();

    if ($lang === 'ku') {
        $kuField = $field . '_ku';
        if (!empty($row[$kuField])) {
            return $row[$kuField];
        }
    } elseif ($lang === 'ar') {
        $arField = $field . '_ar';
        if (!empty($row[$arField])) {
            return $row[$arField];
        }
    }

    // Fallback to English/default name
    return $row[$field] ?? '';
}

// Get localized description
function getLocalizedDescription($row) {
    return getLocalizedName($row, 'description');
}

// Handle language change request
if (isset($_GET['lang']) && in_array($_GET['lang'], ['en', 'ku', 'ar'])) {
    setLang($_GET['lang']);
    // Redirect to remove lang parameter from URL
    $redirectUrl = strtok($_SERVER['REQUEST_URI'], '?');
    $params = $_GET;
    unset($params['lang']);
    if (!empty($params)) {
        $redirectUrl .= '?' . http_build_query($params);
    }
    header('Location: ' . $redirectUrl);
    exit();
}
